// Bundles Bearlett's card rules (bearlett src/cards/mint.ts) into
// server/vendor/lnurlcash-cards.js: the one place the card mint's
// security-critical code comes from, with its tests in Bearlett.
//
//   node scripts/vendor-lnurlcash.mjs <bearlett checkout with npm ci done>
//
// The bundle carries its own dependencies (noble, scure), so the server needs
// nothing new. The provenance file names the commit, and its sha256 pins the
// bytes; tests/js/card-mint.test.mjs checks the two agree.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const source = resolve(process.argv[2] || "");
const git = (...args) => execFileSync("git", ["-C", source, ...args]).toString().trim();
const commit = git("rev-parse", "HEAD");
if (git("status", "--porcelain", "--", "src")) {
  throw new Error("the bearlett checkout has uncommitted changes under src/: bundle a commit");
}
const out = resolve("server/vendor/lnurlcash-cards.js");
mkdirSync(resolve("server/vendor"), { recursive: true });
await build({
  entryPoints: [join(source, "src/cards/mint.ts")],
  absWorkingDir: source,
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node22",
  outfile: out,
  legalComments: "inline",
  banner: { js: `/* Generated by scripts/vendor-lnurlcash.mjs from bearlett ${commit} src/cards/mint.ts. Do not edit. */` },
});
const sha256 = createHash("sha256").update(readFileSync(out)).digest("hex");
writeFileSync(resolve("server/vendor/lnurlcash-cards.provenance.json"), JSON.stringify({
  source: "https://github.com/BIMbeamFLX/bearlett",
  entry: "src/cards/mint.ts",
  commit,
  sha256,
}, null, 2) + "\n");
console.log(`server/vendor/lnurlcash-cards.js ${sha256} (bearlett ${commit.slice(0, 7)})`);
