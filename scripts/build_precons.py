STARTER_META = {
    "Power": ("Power Surge", "Fast rigs, raw watts, quick clashes."),
    "Bitcoin": ("Sound Money", "Patient value that compounds."),
    "Keys": ("Key Custody", "Hold your keys, hold the line."),
    "Signal": ("Open Relay", "Reach everyone, answer everything."),
    "Timelock": ("Patient Circuit", "Slow is smooth, and smooth wins."),
}


def build_precons(cards: list[dict]) -> dict[str, dict]:
    """Every shelf, in a stable order: five Starters, then the Classics."""
    out: dict[str, dict] = {}
    for affinity in AFFINITIES:
        name, tagline = STARTER_META[affinity]
        out[name] = {
            "group": "Starter",
            "affinity": affinity,
            "tagline": tagline,
            "cards": starter(cards, affinity),
        }
    for spec in classics_specs():
        out[spec["name"]] = {
            "group": "Classic",
            "affinity": spec["affinity"],
            "tagline": spec["tagline"],
            "cards": classic(cards, spec),
        }
    for name, precon in out.items():
        if len(precon["cards"]) < 40:
            raise SystemExit(f"{name}: only {len(precon['cards'])} cards - pool too thin")
    return out


def main() -> None:
    cards = load_cards()
    precons = build_precons(cards)
    body = json.dumps(precons, indent=1, ensure_ascii=False)
    exports = (
        'if (typeof module === "object" && module.exports) module.exports = globalThis.E1_PRECONS;'
    )
    OUT.write_text(f"{HEADER}globalThis.E1_PRECONS = {body};\n{exports}\n", encoding="utf-8")
    total = sum(len(p["cards"]) for p in precons.values())
    print(f"wrote {OUT} ({len(precons)} Stacks, {total} cards)")


if __name__ == "__main__":
    main()
